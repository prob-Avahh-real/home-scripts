# 标点符号、数字、英文、注音
PUNCTUATION="，。、；：？！「」『』（）《》【】…—～・．‧·　 　,.;:?!\"'()[]{}…-~・.· 0123456789０１２３４５６７８９ ABCDEFGHIJKLMNOPQRSTUVWXYZ abcdefghijklmnopqrstuvwxyz ＡＢＣＤＥＦＧＨＩＪＫＬＭＮＯＰＱＲＳＴＵＶＷＸＹＺ ａｂｃｄｅｆｇｈｉｊｋｌｍｎｏｐｑｒｓｔｕｖｗｘｙｚ ㄅㄆㄇㄈㄉㄊㄋㄌㄍㄎㄏㄐㄑㄒㄓㄔㄕㄖㄗㄘㄙㄚㄛㄜㄝㄞㄟㄠㄡㄢㄣㄤㄥㄦㄧㄨㄩ"

ALL_TEXT="${TC_CHARS}${PUNCTUATION}"

# ---------- 帮助 ----------
usage() {
    cat <<EOF
用法: $(basename "$0") [选项] <字体文件...>

选项:
  --text "自訂文字"      追加自订文字到字表
  --text-file FILE        从文件读取追加文字
  --woff2                 输出 woff2 格式 (更小, iOS 14+ / Android 支持)
  --output-dir DIR        输出目录 (默认: ./subset-fonts)
  --help                  显示此帮助

示例:
  $(basename "$0") SourceHanSansTC-Regular.otf
  $(basename "$0") --woff2 *.otf
  $(basename "$0") --text "我的App專用詞彙" *.otf
  $(basename "$0") --text-file ui_strings.txt font.otf
EOF
    exit 0
}

# ---------- 解析参数 ----------
FONTS=()
while [[ $# -gt 0 ]]; do
    case "$1" in
        --help|-h) usage ;;
        --woff2) WOFF2_MODE=true; shift ;;
        --output-dir) OUTPUT_DIR="$2"; shift 2 ;;
        --text) EXTRA_TEXT="${EXTRA_TEXT}$2"; shift 2 ;;
        --text-file) TEXT_FILE="$2"; shift 2 ;;
        --*) echo "未知选项: $1"; exit 1 ;;
        *) FONTS+=("$1"); shift ;;
    esac
done

if [[ ${#FONTS[@]} -eq 0 ]]; then
    echo "[错误] 请指定至少一个字体文件"
    usage
fi

# ---------- 检查 fonttools ----------
if ! command -v pyftsubset &>/dev/null; then
    echo "[错误] 未安装 fonttools，请先执行:"
    echo "  pip3 install fonttools brotli"
    exit 1
fi

# ---------- 准备文字 ----------
if [[ -n "$TEXT_FILE" ]]; then
    if [[ ! -f "$TEXT_FILE" ]]; then
        echo "[错误] 找不到文件: $TEXT_FILE"
        exit 1
    fi
    FILE_TEXT=$(cat "$TEXT_FILE" | tr -d '\n')
    ALL_TEXT="${ALL_TEXT}${FILE_TEXT}"
fi

if [[ -n "$EXTRA_TEXT" ]]; then
    ALL_TEXT="${ALL_TEXT}${EXTRA_TEXT}"
fi

# 去重
UNIQUE_CHARS=$(echo "$ALL_TEXT" | grep -o . | sort -u | tr -d '\n')
CHAR_COUNT=$(echo -n "$UNIQUE_CHARS" | wc -m | tr -d ' ')
echo "[字表] 共 ${CHAR_COUNT} 个不重复字符"

# ---------- 处理 ----------
mkdir -p "$OUTPUT_DIR"

for FONT in "${FONTS[@]}"; do
    if [[ ! -f "$FONT" ]]; then
        echo "[跳过] 找不到文件: $FONT"
        continue
    fi

    BASENAME=$(basename "$FONT")
    NAME="${BASENAME%.*}"
    EXT="${BASENAME##*.}"

    if $WOFF2_MODE; then
        OUTFILE="${OUTPUT_DIR}/${NAME}-subset.woff2"
        FLAVOR="--flavor=woff2"
    else
        OUTFILE="${OUTPUT_DIR}/${NAME}-subset.${EXT}"
        FLAVOR=""
    fi

    ORIG_SIZE=$(ls -lh "$FONT" | awk '{print $5}')

    echo ""
    echo "----------------------------------------"
    echo "[处理] $BASENAME"
    echo "  原始大小: $ORIG_SIZE"

    pyftsubset "$FONT" \
        --text="$UNIQUE_CHARS" \
        --output-file="$OUTFILE" \
        --layout-features='*' \
        --desubroutinize \
        --no-hinting \
        --name-IDs='*' \
        $FLAVOR \
        2>&1 | tail -1

    if [[ -f "$OUTFILE" ]]; then
        NEW_SIZE=$(ls -lh "$OUTFILE" | awk '{print $5}')
        echo "  输出大小: $NEW_SIZE"
        echo "  输出路径: $OUTFILE"
    else
        echo "  [失败] 子集化未生成输出文件"
    fi
done

echo ""
echo "========================================"
echo "完成。输出目录: $OUTPUT_DIR"
ls -lh "$OUTPUT_DIR"
